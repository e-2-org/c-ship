"""Glyphs missing from the lettering images, drawn on the same pixel grid as the
artists' names (13px cell, ascender row 3, x-height row 8, baseline under row
20, descender to row 25), then smoothed and traced like the others."""
import json, sys
import numpy as np
from PIL import Image, ImageFilter
import potrace

OUT = sys.argv[1]
ADV, CELL, BASE, UP = 600, 13, 21, 8
U = ADV / CELL

O = ['..#####..', '.#######.', '####.####', '###...###', '##.....##', '##.....##', '##.....##',
     '##.....##', '##.....##', '###...###', '####.####', '.#######.', '..#####..']  # rows 8-20

G = {}
G['p'] = (8, ['#######..', '########.', '####.####', '###...###'] + ['##.....##'] * 5 +
          ['###...###', '####.####', '########.', '#######..'] + ['###......'] * 5)
G['q'] = (8, [r[::-1] for r in G['p'][1]])
G['j'] = (3, ['.....###.', '.....###.', '.........', '.........', '.........'] + ['.....###.'] * 15 +
          ['##..####.', '#######..', '.#####...'])
G['k'] = (3, ['###......'] * 9 + ['###...###', '###..###.', '###.###..', '######...', '#######..',
                                   '###.###..', '###..###.', '###...###', '###....##'])
G['x'] = (8, ['##.....##', '##.....##', '###...###', '.###.###.', '..#####..', '...###...', '..#####..',
              '.###.###.', '###...###', '##.....##', '##.....##', '##.....##', '##.....##'])
G['z'] = (8, ['#########', '#########', '.....####', '.....####', '....####.', '...####..', '..####...',
              '..####...', '.####....', '####.....', '####.....', '#########', '#########'])
G['0'] = (8, O)
G['1'] = (8, ['..###....', '.####....', '#####....'] + ['..###....'] * 8 + ['#########', '#########'])
G['2'] = (8, ['.######..', '########.', '###..####', '......###', '.....####', '....####.', '...####..',
              '..####...', '.####....', '####.....', '###......', '#########', '#########'])
G['3'] = (8, ['#########', '#########', '.....####', '....####.', '...####..', '..######.', '..#######',
              '......###', '.......##', '.......##', '.......##', '.......##', '##.....##', '###...###',
              '####.####', '.#######.', '..#####..'])
G['4'] = (8, ['.....###.', '....####.', '...#####.', '..###.##.', '..##..##.', '.###..##.', '.##...##.',
              '###...##.', '##....##.', '##....##.', '##....##.', '#########', '#########'] + ['......##.'] * 5)
G['5'] = (8, ['########.', '########.', '##.......', '##.......', '##.####..', '########.', '###..####',
              '......###', '.......##', '.......##', '.......##', '.......##', '......###', '##...####',
              '########.', '.######..'])
G['6'] = (3, ['...####..', '..####...', '.####....', '.###.....', '###......', '###.####.', '#########',
              '####.####', '###...###'] + ['##.....##'] * 5 + ['###...###', '####.####', '.#######.', '..#####..'])
G['7'] = (8, ['#########', '#########', '......###', '......###', '.....###.', '.....###.', '....###..',
              '....###..'] + ['...###...'] * 4 + ['..###....'] * 6)
G['8'] = (3, ['..#####..', '.#######.', '###...###', '##.....##', '###...###', '.#######.', '..#####..',
              '.#######.', '###...###'] + ['##.....##'] * 5 + ['###...###', '####.####', '.#######.', '..#####..'])
G['9'] = (8, [r[::-1] for r in reversed(G['6'][1])])
dot = ['...###...'] * 3
G['.'] = (18, dot)
G[','] = (18, dot + ['...##....', '..##.....'])
G[':'] = (9, dot + ['.........'] * 6 + dot)
G[';'] = (9, dot + ['.........'] * 6 + dot + ['...##....', '..##.....'])
G['!'] = (3, ['...###...'] * 13 + ['.........'] * 2 + dot)
G['?'] = (3, ['.######..', '########.', '###..####', '......###', '.....####', '....####.', '...####..',
              '...###...', '...###...', '...###...', '...###...', '...###...', '.........', '.........',
              '.........'] + dot)
G["'"] = (3, ['...###...'] * 4 + ['...##....'])
G['"'] = (3, ['.###.###.'] * 4 + ['.##..##..'])
G['-'] = (13, ['.#######.', '.#######.'])
G['/'] = (3, [('.' * max(0, 7 - i * 7 // 19) + '##').ljust(9, '.')[:9] for i in range(20)])
G['('] = (3, ['.....###.', '....###..', '...###...', '...###...'] + ['..###....'] * 14 +
          ['...###...', '...###...', '....###..', '.....###.'])
G[')'] = (3, [r[::-1] for r in G['('][1]])


def trace(I, x0):
    crop = Image.fromarray((I * 255).astype(np.uint8))
    big = crop.resize((crop.width * UP, crop.height * UP), Image.BICUBIC)
    bm = potrace.Bitmap(np.asarray(big) <= 127)
    out = []
    for curve in bm.trace(turdsize=4 * UP, alphamax=1.1, opticurve=True, opttolerance=0.3):
        pts = [('M', [curve.start_point])]
        for seg in curve.segments:
            if seg.is_corner:
                pts += [('L', [seg.c]), ('L', [seg.end_point])]
            else:
                pts.append(('C', [seg.c1, seg.c2, seg.end_point]))
        out.append([(op, [((p.x / UP - x0) * U, (BASE - p.y / UP) * U) for p in ps]) for op, ps in pts])
    return out


glyphs = {}
for c, (top, rows) in G.items():
    pad = 3
    canvas = np.zeros((30, CELL + 2 * pad))
    for i, r in enumerate(rows):
        for j, ch in enumerate(r):
            if ch == '#':
                canvas[top + i, pad + 2 + j] = 1
    # soften the pixel corners, as the anti-aliased originals are
    im = Image.fromarray((canvas * 255).astype(np.uint8)).filter(ImageFilter.GaussianBlur(0.7))
    glyphs[c] = {'contours': trace(np.asarray(im) / 255, pad), 'source': 'drawn', 'px': CELL}
json.dump(glyphs, open(f'{OUT}/drawn.json', 'w'))
print('drawn:', ''.join(glyphs))
